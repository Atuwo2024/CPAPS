
import os
import json
import joblib
import pandas as pd
import numpy as np

from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline

from sklearn.ensemble import (
    RandomForestClassifier,
    RandomForestRegressor
)

from sklearn.dummy import DummyClassifier, DummyRegressor

from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    f1_score,
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_DIR = os.path.join(BASE_DIR, "ml_outputs")

DATA_PATH = os.path.join(
    MODEL_DIR,
    "prediction_training_data.csv"
)

os.makedirs(MODEL_DIR, exist_ok=True)

# Six inputs supplied by the user
FEATURES = [
    "county",
    "area_type",
    "day_of_week",
    "hour_of_day",
    "month_number",
    "year_number"
]

# Six outputs generated by CPAPS
TARGETS = [
    "crime_type",
    "crime_category",
    "severity_level",
    "property_loss_ksh",
    "injuries_reported",
    "fatalities"
]

CATEGORICAL_FEATURES = [
    "county",
    "area_type",
    "day_of_week"
]

NUMERIC_FEATURES = [
    "hour_of_day",
    "month_number",
    "year_number"
]


def create_preprocessor():

    categorical_pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("encoder", OneHotEncoder(handle_unknown="ignore"))
    ])

    numeric_pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="median"))
    ])

    return ColumnTransformer([
        ("categorical", categorical_pipeline, CATEGORICAL_FEATURES),
        ("numeric", numeric_pipeline, NUMERIC_FEATURES)
    ])


def create_classifier():

    return Pipeline([
        ("preprocessor", create_preprocessor()),
        ("model", RandomForestClassifier(
            n_estimators=300,
            random_state=42,
            min_samples_leaf=2,
            class_weight="balanced"
        ))
    ])


def create_regressor():

    return Pipeline([
        ("preprocessor", create_preprocessor()),
        ("model", RandomForestRegressor(
            n_estimators=300,
            random_state=42,
            min_samples_leaf=2
        ))
    ])


def main():

    print("\n========== CPAPS PREDICTION MODEL TRAINING ==========")

    if not os.path.exists(DATA_PATH):
        print("ERROR: Training dataset not found:", DATA_PATH)
        return

    df = pd.read_csv(DATA_PATH)

    print("\nRecords loaded:", len(df))

    missing = df[FEATURES + TARGETS].isnull().sum()

    if missing.any():
        print("\nERROR: Missing values detected:")
        print(missing)
        return

    # Use one common training and testing split.
    indices = np.arange(len(df))

    train_indices, test_indices = train_test_split(
        indices,
        test_size=0.20,
        random_state=42,
        stratify=df["crime_type"]
    )

    X_train = df.iloc[train_indices][FEATURES]
    X_test = df.iloc[test_indices][FEATURES]

    results = []
    saved_models = {}

    print("\nTraining records:", len(X_train))
    print("Testing records:", len(X_test))

    # Classification targets
    classification_targets = [
        "crime_type",
        "crime_category",
        "severity_level",
        "injuries_reported"
    ]

    for target in classification_targets:

        print(f"\n---------- TRAINING {target.upper()} ----------")

        y_train = df.iloc[train_indices][target]
        y_test = df.iloc[test_indices][target]

        model = create_classifier()

        model.fit(X_train, y_train)

        predictions = model.predict(X_test)

        # Majority-class baseline
        baseline = DummyClassifier(strategy="most_frequent")
        baseline.fit(X_train, y_train)
        baseline_predictions = baseline.predict(X_test)

        accuracy = accuracy_score(y_test, predictions)
        baseline_accuracy = accuracy_score(
            y_test,
            baseline_predictions
        )

        balanced_accuracy = balanced_accuracy_score(
            y_test,
            predictions
        )

        weighted_f1 = f1_score(
            y_test,
            predictions,
            average="weighted",
            zero_division=0
        )

        print("Model accuracy:", round(accuracy, 4))
        print("Baseline accuracy:", round(baseline_accuracy, 4))
        print("Balanced accuracy:", round(balanced_accuracy, 4))
        print("Weighted F1:", round(weighted_f1, 4))

        model_name = target + "_model.pkl"

        joblib.dump(
            model,
            os.path.join(MODEL_DIR, model_name)
        )

        saved_models[target] = model_name

        results.append({
            "target": target,
            "model_type": "classification",
            "accuracy": accuracy,
            "baseline_accuracy": baseline_accuracy,
            "balanced_accuracy": balanced_accuracy,
            "weighted_f1": weighted_f1
        })

    # Regression targets
    regression_targets = [
        "property_loss_ksh",
        "fatalities"
    ]

    for target in regression_targets:

        print(f"\n---------- TRAINING {target.upper()} ----------")

        y_train = df.iloc[train_indices][target].astype(float)
        y_test = df.iloc[test_indices][target].astype(float)

        model = create_regressor()

        model.fit(X_train, y_train)

        predictions = model.predict(X_test)

        # Median baseline
        baseline = DummyRegressor(strategy="median")
        baseline.fit(X_train, y_train)

        baseline_predictions = baseline.predict(X_test)

        mae = mean_absolute_error(y_test, predictions)
        baseline_mae = mean_absolute_error(
            y_test,
            baseline_predictions
        )

        rmse = np.sqrt(mean_squared_error(y_test, predictions))
        r2 = r2_score(y_test, predictions)

        print("Model MAE:", round(mae, 2))
        print("Baseline MAE:", round(baseline_mae, 2))
        print("Model RMSE:", round(rmse, 2))
        print("R-squared:", round(r2, 4))

        model_name = target + "_model.pkl"

        joblib.dump(
            model,
            os.path.join(MODEL_DIR, model_name)
        )

        saved_models[target] = model_name

        results.append({
            "target": target,
            "model_type": "regression",
            "mae": mae,
            "baseline_mae": baseline_mae,
            "rmse": rmse,
            "r2": r2
        })

    # Save evaluation results
    results_df = pd.DataFrame(results)

    evaluation_path = os.path.join(
        MODEL_DIR,
        "prediction_model_evaluation.csv"
    )

    results_df.to_csv(evaluation_path, index=False)

    # Save model file names and input schema
    bundle = {
        "features": FEATURES,
        "targets": TARGETS,
        "models": saved_models
    }

    bundle_path = os.path.join(
        MODEL_DIR,
        "prediction_model_bundle.pkl"
    )

    joblib.dump(bundle, bundle_path)

    print("\n========== TRAINING SUMMARY ==========")
    print(results_df.to_string(index=False))

    print("\nModels saved in:", MODEL_DIR)
    print("Evaluation saved:", evaluation_path)
    print("Model bundle saved:", bundle_path)

    print("\n========== TRAINING COMPLETE ==========")


if __name__ == "__main__":
    main()
